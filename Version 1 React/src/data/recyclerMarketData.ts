function inferLocationFilter(location: string): DashboardLocationFilter {
  const normalized = location.toLowerCase();
  if (normalized.includes("canada") || normalized.includes("ontario") || normalized.includes("quebec")) {
    return "canada";
  }
  if (
    normalized.includes("germany") ||
    normalized.includes("sweden") ||
    normalized.includes("uk") ||
    normalized.includes("france")
  ) {
    return "europe";
  }
  if (normalized.includes("japan") || normalized.includes("korea") || normalized.includes("singapore")) {
    return "asia";
  }
  return "usa";
}

function inferLotSize(quantity: string): DashboardLotSize {
  const match = quantity.match(/[\d,.]+/);
  const numeric = match ? Number(match[0].replace(/,/g, "")) : 0;
  const quantityInTons = quantity.toLowerCase().includes("kg") ? numeric / 1000 : numeric;

  if (quantityInTons >= 15) return "large";
  if (quantityInTons >= 6) return "mid";
  return "small";
}

function makeListing(sourceId: DashboardSourceId, seed: ListingSeed, mode: "live" | "auction"): DashboardBidListing {
  const defaultImages = seed.images ?? [seed.image ?? sourceImages[sourceId][0], ...sourceImages[sourceId].slice(1)];
  return {
    id: seed.id,
    sourceId,
    material: seed.material,
    category: seed.category,
    location: seed.location,
    quantity: seed.quantity,
    openingBid: mode === "auction" ? `${seed.pricePerTon} auction basis` : `${seed.pricePerTon} listed price`,
    concentration: seed.concentration,
    verification: seed.verification,
    purityNotes: seed.purityNotes,
    availability: seed.availability,
    lotSize: inferLotSize(seed.quantity),
    locationFilter: inferLocationFilter(seed.location),
    pricePerTon: seed.pricePerTon,
    availableLots: seed.availableLots,
    sellerName: seed.sellerName,
    sellerType: seed.sellerType,
    image: seed.image ?? sourceImages[sourceId][0],
    images: defaultImages,
    detailTitle: seed.detailTitle,
    detailSummary: seed.detailSummary,
    sourceStream: seed.sourceStream,
    packaging: seed.packaging,
    logistics: seed.logistics,
    recoveryNotes: seed.recoveryNotes,
  };
}

